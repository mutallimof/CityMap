export type StringKey = keyof typeof STRINGS;

function t(lang: Lang, key: StringKey): string {
  return STRINGS[key][lang];
}

/** Human label for an OSM kind (subclass): translated when we know it, else prettified. */
export function kindLabel(kind: string, lang: Lang): string {
  const k = `kind_${kind}` as StringKey;
  if (k in STRINGS) return STRINGS[k][lang];
  const s = kind.replace(/_/g, ' ');
  return s.charAt(0).toUpperCase() + s.slice(1);
}

export function useT(): (key: StringKey) => string {
  const lang = useUi((s) => s.lang);
  return (key) => STRINGS[key][lang];
}

/** "4 dk" / "4 min", "now" under 30 s, "1 h 05" over an hour. */
/** "1 stop" / "3 stops" (Turkish has no plural after a number). */
export const stopsText = (n: number, lang: Lang): string => `${n} ${STRINGS[n === 1 ? 'stop' : 'stops'][lang]}`;

export function formatWait(seconds: number, lang: Lang): string {
  if (seconds < 30) return t(lang, 'now');
  const m = Math.round(seconds / 60);
  if (m < 60) return `${m} ${t(lang, 'min')}`;
  return `${Math.floor(m / 60)} ${lang === 'tr' ? 'sa' : 'h'} ${String(m % 60).padStart(2, '0')}`;
}

/** m:ss countdown. */
export function formatCountdown(seconds: number): string {
  const s = Math.max(0, Math.round(seconds));
  return `${Math.floor(s / 60)}:${String(s % 60).padStart(2, '0')}`;
}
